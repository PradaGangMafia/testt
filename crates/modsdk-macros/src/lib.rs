#![forbid(unsafe_code)]
#![deny(missing_docs)]
//! Procedural macros for the Agent-Fleet module SDK.
//!
//! [`mod_main`] turns an ordinary Rust function into the ABI 1 `handle`
//! export described in `docs/MODS.md`.

use proc_macro::TokenStream;
use proc_macro2::TokenStream as TokenStream2;
use quote::quote;
use syn::{parse_macro_input, Error, FnArg, ItemFn, Pat, ReturnType, Type};

/// Marks a function as the module entry point and emits the ABI 1 shim.
///
/// The annotated function must have the signature
/// `fn(&Ctx) -> Result<(), CapError>`. A different signature is rejected at
/// compile time with a readable error.
#[proc_macro_attribute]
pub fn mod_main(_attr: TokenStream, item: TokenStream) -> TokenStream {
    let function = parse_macro_input!(item as ItemFn);
    match expand(function) {
        Ok(tokens) => tokens.into(),
        Err(error) => error.to_compile_error().into(),
    }
}

fn expand(function: ItemFn) -> Result<TokenStream2, Error> {
    validate_signature(&function)?;
    let name = &function.sig.ident;
    Ok(quote! {
        #function

        /// ABI 1 entry point generated by [`mod_main`].
        #[no_mangle]
        pub extern "C" fn handle(__args_ptr: i32, __args_len: i32) -> i32 {
            let __ctx = match ::modsdk::__ctx_from_args(__args_ptr, __args_len) {
                Ok(ctx) => ctx,
                Err(error) => {
                    ::modsdk::__result_error(&error.to_string());
                    return 1;
                }
            };
            match #name(&__ctx) {
                Ok(()) => 0,
                Err(error) => {
                    ::modsdk::__result_error(&error.to_string());
                    1
                }
            }
        }
    })
}

fn validate_signature(function: &ItemFn) -> Result<(), Error> {
    if function.sig.unsafety.is_some() {
        return Err(Error::new_spanned(
            &function.sig,
            "mod entry points must not be unsafe",
        ));
    }
    if function.sig.asyncness.is_some() {
        return Err(Error::new_spanned(
            &function.sig,
            "mod entry points must not be async",
        ));
    }

    let mut inputs = function.sig.inputs.iter();
    let argument = match (inputs.next(), inputs.next()) {
        (Some(FnArg::Typed(argument)), None) => argument,
        _ => return Err(signature_error(&function.sig)),
    };
    if !matches!(&*argument.pat, Pat::Ident(_)) {
        return Err(signature_error(&function.sig));
    }
    if !is_shared_ctx(&argument.ty) {
        return Err(signature_error(&function.sig));
    }

    match &function.sig.output {
        ReturnType::Type(_, ty) if is_result_unit(ty) => Ok(()),
        _ => Err(signature_error(&function.sig)),
    }
}

fn signature_error(signature: &syn::Signature) -> Error {
    Error::new_spanned(
        signature,
        "mod entry point must have the signature `fn(&Ctx) -> Result<(), CapError>`",
    )
}

/// Matches `&Ctx` and `&modsdk::Ctx`.
fn is_shared_ctx(ty: &Type) -> bool {
    let Type::Reference(reference) = ty else {
        return false;
    };
    if reference.mutability.is_some() {
        return false;
    }
    type_ends_with(&reference.elem, "Ctx")
}

/// Matches `Result<(), CapError>` and `std::result::Result<(), modsdk::CapError>`.
fn is_result_unit(ty: &Type) -> bool {
    let Type::Path(path) = ty else {
        return false;
    };
    let Some(segment) = path.path.segments.last() else {
        return false;
    };
    if segment.ident != "Result" {
        return false;
    }
    let syn::PathArguments::AngleBracketed(arguments) = &segment.arguments else {
        return false;
    };
    if arguments.args.len() != 2 {
        return false;
    }
    let mut args = arguments.args.iter();
    let ok = args.next();
    let error = args.next();
    matches!(ok, Some(syn::GenericArgument::Type(Type::Tuple(tuple))) if tuple.elems.is_empty())
        && matches!(error, Some(syn::GenericArgument::Type(error)) if type_ends_with(error, "CapError"))
}

fn type_ends_with(ty: &Type, name: &str) -> bool {
    let Type::Path(path) = ty else {
        return false;
    };
    path.path
        .segments
        .last()
        .is_some_and(|segment| segment.ident == name)
}

#[cfg(test)]
mod tests {
    use super::*;
    use syn::parse_quote;

    fn expansion(source: &str) -> Result<String, String> {
        let function: ItemFn = syn::parse_str(source).expect("function parses");
        expand(function)
            .map(|tokens| tokens.to_string())
            .map_err(|error| error.to_string())
    }

    #[test]
    fn accepts_the_documented_signature_and_invokes_the_function() {
        let tokens =
            expansion("fn scan(ctx: &Ctx) -> Result<(), CapError> { ctx.log(\"hi\"); Ok(()) }")
                .expect("valid signature");
        assert!(tokens.contains("fn handle"), "{tokens}");
        assert!(tokens.contains("__ctx_from_args"), "{tokens}");
        assert!(tokens.contains("scan (& __ctx)"), "{tokens}");
        assert!(tokens.contains("__result_error"), "{tokens}");
    }

    #[test]
    fn accepts_qualified_types() {
        expansion(
            "fn scan(ctx: &modsdk::Ctx) -> std::result::Result<(), modsdk::CapError> { Ok(()) }",
        )
        .expect("qualified signature is valid");
    }

    #[test]
    fn rejects_wrong_signatures_with_a_readable_message() {
        for source in [
            "fn scan() -> Result<(), CapError> { Ok(()) }",
            "fn scan(ctx: &Ctx) -> i32 { 0 }",
            "fn scan(ctx: &mut Ctx) -> Result<(), CapError> { Ok(()) }",
            "fn scan(ctx: Ctx) -> Result<(), CapError> { Ok(()) }",
            "fn scan(ctx: &Ctx) -> Result<u8, CapError> { Ok(0) }",
            "fn scan(ctx: &Ctx) -> Result<(), String> { Ok(()) }",
            "fn scan(ctx: &Ctx, extra: i32) -> Result<(), CapError> { Ok(()) }",
            "async fn scan(ctx: &Ctx) -> Result<(), CapError> { Ok(()) }",
        ] {
            let error = expansion(source).expect_err(source);
            assert!(
                error.contains("fn(&Ctx) -> Result<(), CapError>")
                    || error.contains("must not be async")
                    || error.contains("must not be unsafe"),
                "{source}: {error}"
            );
        }
    }

    #[test]
    fn keeps_the_annotated_items_and_adds_one_export() {
        let tokens =
            expansion("#[doc = \"scan\"] fn scan(_ctx: &Ctx) -> Result<(), CapError> { Ok(()) }")
                .expect("valid signature");
        assert_eq!(tokens.matches("fn handle").count(), 1, "{tokens}");
        assert!(tokens.contains("# [doc = \"scan\"]"), "{tokens}");
    }

    #[test]
    fn parses_the_ctx_reference_shape() {
        let ty: Type = parse_quote!(&'static Ctx);
        assert!(is_shared_ctx(&ty));
        let ty: Type = parse_quote!(&mut Ctx);
        assert!(!is_shared_ctx(&ty));
    }
}
